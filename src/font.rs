// ============================================================================
// 字符查找辅助函数 (Character Lookup Helper Functions)
// ============================================================================

/// 根据ASCII数字字符获取对应的点阵数据 (Get bitmap data for ASCII digit)
///
/// # 参数 (Parameters)
/// - `digit`: ASCII数字字符 '0'-'9' 或 '.' (ASCII digit character '0'-'9' or '.')
///
/// # 返回 (Returns)
/// - `Some(&[[u8; 2]; 16])`: 点阵数据引用 (Bitmap data reference)
/// - `None`: 不支持的字符 (Unsupported character)
pub fn get_digit_bitmap(digit: char) -> Option<&'static [[u8; 2]; 16]> {
    match digit {
        '0' => Some(&CHAR_DIGIT_0),
        '1' => Some(&CHAR_DIGIT_1),
        '2' => Some(&CHAR_DIGIT_2),
        '3' => Some(&CHAR_DIGIT_3),
        '4' => Some(&CHAR_DIGIT_4),
        '5' => Some(&CHAR_DIGIT_5),
        '6' => Some(&CHAR_DIGIT_6),
        '7' => Some(&CHAR_DIGIT_7),
        '8' => Some(&CHAR_DIGIT_8),
        '9' => Some(&CHAR_DIGIT_9),
        '.' => Some(&CHAR_DOT),
        _ => None,
    }
}
